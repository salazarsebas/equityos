/**
 * Regenerates the typed ABI modules in `src` from the Foundry build artifacts.
 *
 *   forge build --root contracts && bun run --filter @equityos/contracts-abi generate
 *
 * The ABI is written as a TypeScript `as const` literal because a JSON import does not keep the literal types
 * that typed contract calls are inferred from. `test/abi.test.ts` fails when a module and its artifact differ.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ABI_SOURCES, artifactAbi } from "./sources.ts";

for (const { contract, exportName, module } of ABI_SOURCES) {
  const target = fileURLToPath(new URL(`../src/${module}`, import.meta.url));
  const header = `/** ABI of \`${contract}\`. Generated by \`scripts/generate.ts\` from the Foundry artifact: do not edit. */`;
  writeFileSync(target, `${header}\nexport const ${exportName} = ${JSON.stringify(artifactAbi(contract))} as const;\n`);
  const formatted = Bun.spawnSync(["bunx", "biome", "format", "--write", target], { stderr: "inherit" });
  if (formatted.exitCode !== 0) throw new Error(`biome could not format ${target}`);
  console.log(`${module}: ${readFileSync(target, "utf8").split("\n").length} lines`);
}
